"""
Retrieval experiment (Part 5): which chunking strategy finds the answers, and does hybrid search help?

    python knowledge/experiment.py

For every question in knowledge/questions.json, a hit at 3 means one of the top 3 chunks contains
the question's answer text (word for word, ignoring case and line breaks), as in
memory_examples/ch07_07_chunking_experiment.py. Runs locally: no model or API calls, only embeddings.

Writes knowledge/results.md: the recall table for Workbook B, and every miss, for the write-up.
The last configuration built is the one the search_music_knowledge tool uses.
"""

import json
import sys
from pathlib import Path

KNOWLEDGE_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(KNOWLEDGE_DIR.parent))

import semantic  # noqa: E402

QUESTIONS_PATH = KNOWLEDGE_DIR / "questions.json"
RESULTS_PATH = KNOWLEDGE_DIR / "results.md"


def normalize(text: str) -> str:
    """Lowercase and collapse whitespace, so line breaks inside a chunk don't hide an answer."""
    return " ".join(text.split()).lower()


def check_answers_exist(documents: list[dict], questions: list[dict]) -> None:
    """An answer that isn't in the corpus could never be a hit, so stop before measuring anything."""
    corpus = normalize(" ".join(document["text"] for document in documents))
    missing = []
    for question in questions:
        if normalize(question["answer"]) not in corpus:
            missing.append(question["answer"])
    if missing:
        raise SystemExit("These answers don't appear word for word in the corpus:\n  " + "\n  ".join(missing))


def recall_at(questions: list[dict], strategy: str, hybrid: bool, k: int) -> tuple[int, list[dict]]:
    """How many questions have their answer in the top k chunks, and the details of each miss."""
    hits = 0
    misses = []
    for question in questions:
        results = semantic.search(question["question"], strategy=strategy, k=k, hybrid=hybrid)
        answer = normalize(question["answer"])
        found = False
        for result in results:
            if answer in normalize(result["text"]):
                found = True
        if found:
            hits += 1
        else:
            if results:
                top = f"{results[0]['title']} › {results[0]['section']}"
            else:
                top = "(nothing)"
            misses.append({"question": question["question"], "answer": question["answer"], "top_result": top})
    return hits, misses


def chunk_stats(strategy: str, documents: list[dict]) -> dict:
    chunks = semantic.make_chunks(strategy, documents)
    sizes = [semantic.token_count(chunk["text"]) for chunk in chunks]
    return {"chunks": len(chunks), "max_tokens": max(sizes), "mean_tokens": round(sum(sizes) / len(sizes))}


def main() -> None:
    documents = semantic.load_documents()
    questions = json.loads(QUESTIONS_PATH.read_text(encoding="utf-8"))
    check_answers_exist(documents, questions)
    total = len(questions)
    print(f"{len(documents)} documents, {total} questions, embedding model {semantic.EMBEDDING_MODEL}\n")

    rows = []
    all_misses = {}

    # A and B: the two chunking strategies, vector search only, same corpus and questions.
    for strategy in semantic.STRATEGIES:
        semantic.build(strategy, documents)
        stats = chunk_stats(strategy, documents)
        hits1, _ = recall_at(questions, strategy, hybrid=False, k=1)
        hits3, misses = recall_at(questions, strategy, hybrid=False, k=3)
        name = f"{strategy} (vector)"
        rows.append((name, stats, hits1, hits3))
        all_misses[name] = misses
        print(f"{name:<22} {stats['chunks']:>5} chunks   recall@1 {hits1}/{total}   recall@3 {hits3}/{total}")

    # The improvement: hybrid search on top of the better strategy.
    best = max(rows, key=lambda row: row[3])[0].split(" ")[0]
    semantic.build(best, documents)                      # rebuild last, so the tool uses this one
    stats = chunk_stats(best, documents)
    hits1, _ = recall_at(questions, best, hybrid=True, k=1)
    hits3, misses = recall_at(questions, best, hybrid=True, k=3)
    name = f"{best} + hybrid (BM25)"
    rows.append((name, stats, hits1, hits3))
    all_misses[name] = misses
    print(f"{name:<22} {stats['chunks']:>5} chunks   recall@1 {hits1}/{total}   recall@3 {hits3}/{total}")

    if best != semantic.CHOSEN_STRATEGY:
        print(f"\nNote: '{best}' scored best, but semantic.CHOSEN_STRATEGY is '{semantic.CHOSEN_STRATEGY}'. Update it.")

    lines = ["# Semantic retrieval results", "",
             f"Corpus: {len(documents)} documents. Questions: {total}. Embedding model: {semantic.EMBEDDING_MODEL} "
             f"(limit {semantic.MODEL_TOKEN_LIMIT} tokens). Generated by knowledge/experiment.py.", "",
             "| Configuration | Chunks | Max / mean tokens | Recall@1 | Top-3 Recall |",
             "|---|---|---|---|---|"]
    for name, stats, hits1, hits3 in rows:
        lines.append(f"| {name} | {stats['chunks']} | {stats['max_tokens']} / {stats['mean_tokens']} | "
                     f"{hits1}/{total} | {hits3}/{total} ({100 * hits3 / total:.0f}%) |")
    lines += ["", "Fixed = 256-token windows with 32-token overlap. Sections = one chunk per heading "
                  "(each API endpoint or glossary term), split only when longer than the model's limit.", ""]
    for name, misses in all_misses.items():
        lines.append(f"## Misses: {name}")
        lines.append("")
        if not misses:
            lines.append("None.")
        for miss in misses:
            lines.append(f"- {miss['question']} (answer: \"{miss['answer']}\"; top result: {miss['top_result']})")
        lines.append("")
    RESULTS_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {RESULTS_PATH.relative_to(KNOWLEDGE_DIR.parent)}")


if __name__ == "__main__":
    main()
